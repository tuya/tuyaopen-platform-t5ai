static void __dvp_reg_update(const uint8_t sensor_reg_table[][2], uint32_t size)
{
    uint16_t val_len = sizeof(sensor_reg_table[0][0]);
    for (uint16_t idx = 0; idx < size; idx++)
	{
		SENSOR_I2C_WRITE(sensor_reg_table[idx][0], &(sensor_reg_table[idx][1]), val_len);
	}
}

OPERATE_RET dvp_ov2640_init(TUYA_DVP_CFG_T *cfg)
{
    // update init config
	uint32_t size = sizeof(sensor_dvp_ov2640_init_talbe) / sizeof(sensor_dvp_ov2640_init_talbe[0]);
    __dvp_reg_update(sensor_dvp_ov2640_init_talbe, size);

	//TODO: update fmt
	/*
	extern const TUYA_DVP_SENSOR_CFG_T dvp_sensor_ov2640_cfg;
	TUYA_FRAME_FMT_E fmt = dvp_sensor_ov2640_cfg.fmt;
	*/

    // update ppi
    camera_ppi_t usr_ppi = (cfg->width << 16) | cfg->height;
    switch (usr_ppi)
    {
    case TY_CAMERA_PPI_1600X1200:
        size = sizeof(sensor_dvp_ov2640_1600X1200_talbe) / sizeof(sensor_dvp_ov2640_1600X1200_talbe[0]);
        __dvp_reg_update(sensor_dvp_ov2640_1600X1200_talbe, size);
        break;
    case TY_CAMERA_PPI_1280X720:
        size = sizeof(sensor_dvp_ov2640_1280X720_talbe) / sizeof(sensor_dvp_ov2640_1280X720_talbe[0]);
        __dvp_reg_update(sensor_dvp_ov2640_1280X720_talbe, size);
        break;
    case TY_CAMERA_PPI_800X600:
        size = sizeof(sensor_dvp_ov2640_800X600_talbe) / sizeof(sensor_dvp_ov2640_800X600_talbe[0]);
        __dvp_reg_update(sensor_dvp_ov2640_800X600_talbe, size);
        break;
    case TY_CAMERA_PPI_640X480:
        size = sizeof(sensor_dvp_ov2640_640X480_talbe) / sizeof(sensor_dvp_ov2640_640X480_talbe[0]);
        __dvp_reg_update(sensor_dvp_ov2640_640X480_talbe, size);
        break;
    default:
        break;
    }

	return OPRT_OK;
}

